const express = require("express");
const { setupAdmin, loginAdmin, adminSession, requireAdmin, requireRole, logoutAdmin } = require("../middleware/adminAuth");
const adminController = require("../controllers/adminController");
const operationsController = require("../controllers/adminOperationsController");

const router = express.Router();
router.post("/setup", setupAdmin);
router.post("/login", loginAdmin);
router.get("/session", adminSession);
router.post("/logout", requireAdmin, logoutAdmin);
router.get("/overview", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.overview);
router.get("/assignees", requireAdmin, requireRole("Super Admin", "Administrator"), adminController.listAssignees);
router.get("/registrations", requireAdmin, operationsController.listRegistrations);
router.patch("/registrations/:id", requireAdmin, operationsController.updateRegistration);
router.get("/service-requests", requireAdmin, operationsController.listServiceRequests);
router.patch("/service-requests/:id", requireAdmin, operationsController.updateServiceRequest);
router.get("/corporate-training-requests", requireAdmin, operationsController.listCorporateTrainingRequests);
router.patch("/corporate-training-requests/:id", requireAdmin, operationsController.updateCorporateTrainingRequest);
router.get("/courses", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.listCourses);
router.post("/courses", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.createCourse);
router.patch("/courses/:id", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.updateCourse);
router.get("/clients", requireAdmin, operationsController.listClients);
router.post("/clients", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.saveClient);
router.get("/clients/:id/history", requireAdmin, operationsController.clientHistory);
router.patch("/clients/:id", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.saveClient);
router.get("/announcements", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.listAnnouncements);
router.post("/announcements", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.saveAnnouncement);
router.patch("/announcements/:id", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.saveAnnouncement);
router.get("/reports/:type.csv", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.reportCsv);
router.get("/reports/:type", requireAdmin, requireRole("Super Admin", "Administrator"), operationsController.reportData);
router.get("/staff", requireAdmin, requireRole("Super Admin"), adminController.listStaff);
router.post("/staff", requireAdmin, requireRole("Super Admin"), adminController.createStaff);
router.patch("/staff/:id", requireAdmin, requireRole("Super Admin"), adminController.updateStaff);
router.patch("/staff/:id/password", requireAdmin, requireRole("Super Admin"), adminController.resetStaffPassword);
router.get("/audit-logs", requireAdmin, requireRole("Super Admin"), adminController.auditLogs);
router.get("/applications", requireAdmin, adminController.listApplications);
router.patch("/applications/:id", requireAdmin, adminController.updateApplication);
router.get("/opportunities", requireAdmin, requireRole("Super Admin", "Administrator"), adminController.listOpportunities);
router.post("/opportunities", requireAdmin, requireRole("Super Admin", "Administrator"), adminController.createOpportunity);
router.patch("/opportunities/:id", requireAdmin, requireRole("Super Admin", "Administrator"), adminController.updateOpportunity);
module.exports = router;